#!/bin/sh
# Vendor the ferraus and pixelox agent skills into Rocinante's built-in
# skill library, pinned to release tags:
#
#   scripts/vendor-skills.sh                    # default tags below
#   FERRAUS_TAG=v0.1.5 scripts/vendor-skills.sh # bump one
#   FERRAUS_SRC=../ferraus PIXELOX_SRC=../pixelox scripts/vendor-skills.sh
#                                               # local clones (must have the tags)
#
# Each skills/<name>/SKILL.md becomes builtin/<name>.md with a Rocinante-only
# `requires: [<tool>]` frontmatter line, so loading it tells the model to
# install the CLI through the `toolbox` tool when it is missing. Companion
# files (references/, scripts/) are copied to builtin/<name>/ and listed in
# the generated builtin/vendored.rs; `evals/` is skipped. Run it once per
# Rocinante release; the output is committed and compiled into the binary.
set -eu

FERRAUS_TAG="${FERRAUS_TAG:-v0.1.4}"
PIXELOX_TAG="${PIXELOX_TAG:-v0.4.0}"

cd "$(dirname "$0")/.."
OUT="crates/rocinante-core/src/skills/builtin"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# fetch <repo> <tag> <local-src-or-empty> <dest>
fetch() {
    if [ -n "$3" ]; then
        mkdir -p "$4"
        git -C "$3" archive "$2" skills | tar -x -C "$4"
    else
        git clone --quiet --depth 1 --branch "$2" "https://github.com/$1.git" "$4"
    fi
}

fetch djynnius/ferraus "$FERRAUS_TAG" "${FERRAUS_SRC:-}" "$WORK/ferraus"
fetch djynnius/pixelox "$PIXELOX_TAG" "${PIXELOX_SRC:-}" "$WORK/pixelox"

GEN="$OUT/vendored.rs"
{
    echo "// Generated by scripts/vendor-skills.sh from ferraus $FERRAUS_TAG and"
    echo "// pixelox $PIXELOX_TAG. Do not edit; re-run the script."
    echo
    echo "/// Vendored ferraus/pixelox skills: (name, SKILL.md with \`requires\`)."
    echo "pub(crate) const VENDORED_SKILLS: &[&str] = &["
} > "$GEN"
FILES="$WORK/files.rs"
: > "$FILES"

for tool in ferraus pixelox; do
    for dir in "$WORK/$tool"/skills/*/; do
        name=$(basename "$dir")
        [ -f "$dir/SKILL.md" ] || continue
        # Insert `requires:` after the frontmatter's name line.
        awk -v tool="$tool" '
            NR == 1 { print; next }
            !done && /^name:/ { print; print "requires: [" tool "]"; done = 1; next }
            { print }
        ' "$dir/SKILL.md" > "$OUT/$name.md"
        echo "    include_str!(\"$name.md\")," >> "$GEN"

        rm -rf "${OUT:?}/$name"
        companions=$(cd "$dir" && find . -type f ! -name SKILL.md ! -path './evals/*' | sed 's|^\./||' | sort)
        [ -n "$companions" ] || continue
        const=$(printf '%s' "$name" | tr 'a-z-' 'A-Z_')_FILES
        echo "const $const: &[BundledFile] = &[" >> "$FILES"
        for f in $companions; do
            mkdir -p "$OUT/$name/$(dirname "$f")"
            cp "$dir/$f" "$OUT/$name/$f"
            printf '    BundledFile {\n        name: "%s",\n        bytes: include_bytes!("%s/%s"),\n    },\n' \
                "$f" "$name" "$f" >> "$FILES"
        done
        echo "];" >> "$FILES"
        echo "(\"$name\", $const)," >> "$WORK/table"
    done
done

{
    echo "];"
    echo
    cat "$FILES"
    echo
    echo "/// Companion files per vendored skill."
    echo "pub(crate) fn vendored_files(skill: &str) -> &'static [BundledFile] {"
    echo "    match skill {"
    sed 's|^("\(.*\)", \(.*\)),$|        "\1" => \2,|' "$WORK/table"
    echo "        _ => &[],"
    echo "    }"
    echo "}"
} >> "$GEN"

# Keep `cargo fmt --check` clean.
if command -v rustfmt >/dev/null 2>&1; then
    rustfmt --edition 2024 "$GEN"
fi

echo "vendored ferraus $FERRAUS_TAG and pixelox $PIXELOX_TAG skills into $OUT (see $GEN)"
